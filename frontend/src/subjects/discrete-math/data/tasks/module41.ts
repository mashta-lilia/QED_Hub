// Pure-TS ring layout (data file stays JSX-free).
function ring(n: number, r = 140, cx = 260, cy = 185): GraphNode[] {
  return Array.from({ length: n }, (_, i) => {
    const a = -Math.PI / 2 + (2 * Math.PI * i) / n;
    const id = String(i + 1);
    return { id, label: id, x: Math.round(cx + r * Math.cos(a)), y: Math.round(cy + r * Math.sin(a)) };
  });
}

