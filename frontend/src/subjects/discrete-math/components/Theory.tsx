/* ============================ THEORY PRIMITIVES ============================ */
export function Def({ label, text, note }: { label?: string; text: string; note?: string }) {
  return (
    <div className="th-def">
      <div className="th-def-tag">{label || 'Означення'}</div>
      <RichText tag="p" className="th-def-body" text={text} />
      {note && <RichText tag="p" className="th-note" text={note} />}
    </div>
  );
}
export function Thm({ n, name, text }: { n: string; name?: string; text: string }) {
  return (
    <div className="th-thm">
      <div className="th-thm-head">
        <span className="th-thm-badge">{n}</span>
        {name && <span className="th-thm-name">{name}</span>}
      </div>
      <RichText tag="p" className="th-thm-body" text={text} />
    </div>
  );
}
export function Call({ text, eq, note }: { text?: string; eq?: string; note?: string }) {
  return (
    <div className="th-call">
      {text && <RichText tag="p" text={text} />}
      {eq && (
        <div className="th-bigmath">
          <Tex tex={eq} display />
        </div>
      )}
      {note && <RichText tag="p" className="th-note" text={note} />}
    </div>
  );
}
export function Lead({ text }: { text: string }) {
  return <RichText tag="p" className="th-lead2" text={text} />;
}

